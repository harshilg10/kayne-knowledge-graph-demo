def llm_available() -> bool:
    """True when Claude credentials are configured and LLM use is not disabled."""
    if os.getenv("KG_LLM_DISABLED", "").strip().lower() in {"1", "true", "yes"}:
        return False
    return bool(os.getenv("ANTHROPIC_API_KEY") or os.getenv("ANTHROPIC_AUTH_TOKEN"))


