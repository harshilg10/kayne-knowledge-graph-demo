"""Exports the demo queries as a Neo4j Browser query pack (neo4j/demo_queries.cypher).

    python -m kgdemo.export_queries
"""
from __future__ import annotations

import json

from .config import ROOT
from .queries import QUERIES

OUT = ROOT / "neo4j" / "demo_queries.cypher"


def _cypher_literal(value) -> str:
    if isinstance(value, str):
        return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"
    return json.dumps(value)


def export(path=OUT) -> str:
    params: dict = {}
    for q in QUERIES:
        for k, v in q.params.items():
            if k in params and params[k] != v:
                raise ValueError(f"parameter {k} has conflicting defaults")
            params[k] = v
    lines = [
        "// =====================================================================================",
        "// Knowledge Graph Demo - Neo4j Browser query pack (generated by kgdemo/export_queries.py)",
        "// 1. Open http://localhost:7474/browser/ and connect.",
        "// 2. Optional styling: run  :style  and drag neo4j/browser_style.grass into the style panel.",
        "// 3. Run the :params line below once, then run any query (copy one block at a time).",
        "// =====================================================================================",
        "",
        ":params {" + ", ".join(f"{k}: {_cypher_literal(v)}" for k, v in params.items()) + "}",
        "",
    ]
    for i, q in enumerate(QUERIES, start=1):
        lines.append(f"// ---- {i:02d}. {q.title}")
        lines.append(f"// Q: {q.question}")
        if q.talking_point:
            lines.append(f"// Why it matters: {q.talking_point}")
        lines.append(q.cypher.rstrip() + ";")
        lines.append("")
    text = "\n".join(lines)
    path.write_text(text)
    return text


if __name__ == "__main__":
    export()
    print(f"wrote {OUT.relative_to(ROOT)} ({len(QUERIES)} queries)")
